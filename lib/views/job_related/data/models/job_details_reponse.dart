      jobId: json['jobId'],
      opportunityType: json['opportunityType'],
      jobType: json['jobType'],
      jobProfile: json['jobProfile'],
      jobDescription: json['jobDescription'],
      jobTime: json['jobTime'],
      daysInOffice: json['daysInOffice'],
      cityChoice: json['cityChoice'],
