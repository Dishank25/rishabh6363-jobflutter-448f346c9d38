          jobProfile: jobProfile,
          jobDescription: jobDescription,
          jobTime: jobTime,
          daysInOffice: daysInOffice,
          cityChoice: cityChoice,
          skillsRequired: skillsRequired,
          skillRequiredNote: skillRequiredNote,
